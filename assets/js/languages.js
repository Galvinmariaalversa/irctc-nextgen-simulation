// Get language from localStorage or default to English
function getCurrentLanguage() {
    return localStorage.getItem('selectedLanguage') || 'en';
}

// Get translation text
function t(key) {
    const lang = getCurrentLanguage();
    return translations[lang][key] || translations['en'][key];
}

// Change language
function changeLanguage(lang) {
    localStorage.setItem('selectedLanguage', lang);
    setupInternationalization();
    updatePageLanguage();
    
    // Call page-specific translation updates if defined
    if (typeof updateSearchSummary === 'function') {
        updateSearchSummary();
    }
    if (typeof updateBookingSummary === 'function') {
        updateBookingSummary();
    }
}

// Build a map of lowercase, normalized English strings to translation keys
let englishToKeyMap = null;
function buildEnglishToKeyMap() {
    englishToKeyMap = {};
    if (translations && translations.en) {
        Object.entries(translations.en).forEach(([key, value]) => {
            if (typeof value === 'string') {
                const normalized = value.trim().replace(/\s+/g, ' ').toLowerCase();
                if (normalized) {
                    englishToKeyMap[normalized] = key;
                }
            }
        });
    }
}

// Automatically annotate DOM elements with data-i18n / data-i18n-placeholder based on English text
function setupInternationalization() {
    if (!englishToKeyMap) {
        buildEnglishToKeyMap();
    }
    
    // Annotate title
    const titleElement = document.querySelector('title');
    if (titleElement && !titleElement.hasAttribute('data-i18n')) {
        const titleText = titleElement.textContent.trim().replace(/\s+/g, ' ').toLowerCase();
        const key = englishToKeyMap[titleText];
        if (key) {
            titleElement.setAttribute('data-i18n', key);
        }
    }

    const body = document.body;
    if (!body) return;
    
    const walker = document.createTreeWalker(body, NodeFilter.SHOW_ELEMENT, null, false);
    let element;
    while (element = walker.nextNode()) {
        const tagName = element.tagName.toLowerCase();
        if (tagName === 'script' || tagName === 'style' || tagName === 'textarea' || tagName === 'iframe') {
            continue;
        }
        
        // 1. Placeholder translation matching
        if (element.hasAttribute('placeholder')) {
            const placeholderVal = element.getAttribute('placeholder').trim().replace(/\s+/g, ' ').toLowerCase();
            const key = englishToKeyMap[placeholderVal];
            if (key && !element.hasAttribute('data-i18n-placeholder')) {
                element.setAttribute('data-i18n-placeholder', key);
            }
        }
        
        // 2. Element text content matching
        // Only target elements that do not have child elements (leaf nodes) to preserve sub-markup like <i> icons
        if (element.children.length === 0) {
            const textVal = element.textContent.trim().replace(/\s+/g, ' ').toLowerCase();
            const key = englishToKeyMap[textVal];
            if (key && !element.hasAttribute('data-i18n')) {
                element.setAttribute('data-i18n', key);
            }
        }
    }
}

// Update all page text based on selected language
function updatePageLanguage() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        element.textContent = t(key);
    });
    
    // Update placeholders
    const inputElements = document.querySelectorAll('[data-i18n-placeholder]');
    inputElements.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        element.placeholder = t(key);
    });
    
    // Update title
    const titleEl = document.querySelector('title');
    if (titleEl) {
        const titleKey = titleEl.getAttribute('data-i18n');
        if (titleKey) {
            titleEl.textContent = t(titleKey) || 'IRCTC — Indian Railway Ticket Booking';
        }
    }
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    setupInternationalization();
    updatePageLanguage();
    
    // Set language selector to current language
    const languageSelector = document.getElementById('languageSelector');
    if (languageSelector) {
        languageSelector.value = getCurrentLanguage();
    }
});
